// Bundles the pure server logic (engine + bots + services) into one ESM file
// the Deno Edge Functions import. Run before `supabase functions serve|deploy`.
import { build } from "esbuild";
import { mkdirSync } from "node:fs";

mkdirSync("supabase/functions/_shared", { recursive: true });
await build({
  entryPoints: ["packages/server/src/index.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  outfile: "supabase/functions/_shared/katan.bundle.js",
  external: ["postgres"],
  banner: { js: "// Generated by scripts/build-functions.mjs — do not edit." },
  logLevel: "info",
});
